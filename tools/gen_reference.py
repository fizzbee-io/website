MAX_TRACE_LINES = 40


def clean_baseline(text):
    """Return the expected-result lines shown on the page."""
    out = []
    lines = text.splitlines()
    i = 0
    while i < len(lines):
        s = lines[i].strip()
        i += 1
        if not s:
            continue
        if re.match(r"^Nodes:\s*\d+", s):
            if re.search(r",\s*queued:\s*0\b", s):
                out.append(re.sub(r",\s*elapsed:.*$", "", s))
            continue
        if any(s.startswith(p) for p in SKIP_PREFIXES) or re.search(r"run_\d{4}-\d{2}-\d{2}", s):
            continue
        if s.startswith("FAILED:"):
            out.append(re.sub(r"\s{2,}", " ", s))
            # Keep the counterexample trace that follows, up to the file dumps.
            trace = []
            while i < len(lines) and not lines[i].startswith(("Writen", "To generate")):
                if lines[i].strip():
                    trace.append(lines[i].rstrip())
                i += 1
            if len(trace) > MAX_TRACE_LINES:
                trace = trace[:MAX_TRACE_LINES] + ["... (trace truncated)"]
            out.extend(trace)
            continue
        if any(s.startswith(p) for p in KEEP_PREFIXES):
            out.append(re.sub(r"\s{2,}", " ", s))
    return out


def parse_duration(s):
    m = re.match(r"([\d.]+)\s*(ns|µs|us|ms|s|m)\b", s)
    if not m:
        return 0.0
    v = float(m.group(1))
    return v * {"ns": 1e-9, "µs": 1e-6, "us": 1e-6, "ms": 1e-3, "s": 1, "m": 60}[m.group(2)]


def baseline_cost(text):
    """(seconds, nodes) recorded in a baseline."""
    secs = sum(parse_duration(m) for m in re.findall(r"Time taken[^:]*:\s*(\S+)", text))
    nodes = [int(n) for n in re.findall(r"^Nodes:\s*(\d+)", text, re.M)]
    return secs, max(nodes, default=0)


# --- helpers ---

def slugify(text):
    """GitHub/Hugo-style heading id."""
    s = text.strip().lower()
    s = re.sub(r"[^\w\- ]", "", s)
    return s.replace(" ", "-")


def git_lastmod(checkout, *paths):
    out = subprocess.run(
        ["git", "-C", str(checkout), "log", "-1", "--format=%cI", "--", *paths],
        capture_output=True, text=True, check=True,
    ).stdout.strip()
    return out or None


def front_matter(fields):
    lines = ["---", GENERATED_MARKER]
    for k, v in fields.items():
        if v is None:
            continue
        lines.append(f"{k}: {json.dumps(v, ensure_ascii=False)}")
    lines.append("---")
    return "\n".join(lines) + "\n"


def no_dashes(text):
    """Site copy style: no em or en dashes."""
    return re.sub(r"\s*[\u2014\u2013]\s*|\s+--\s+", ", ", text)


MAX_DESCRIPTION = 220


def meta_description(text, suffix):
    """Meta description from a paragraph: whole sentences only, never cut
    mid-thought (search engines truncate long ones themselves), padded with
    suffix when short."""
    text = no_dashes(re.sub(r"\s+", " ", re.sub(r"[`*_]", "", text)).strip())
    if len(text) > MAX_DESCRIPTION:
        kept = ""
        for sentence in re.split(r"(?<=[.!?])\s+", text):
            if kept and len(kept) + len(sentence) + 1 > MAX_DESCRIPTION:
                break
            kept = f"{kept} {sentence}".strip()
        text = kept
    text = re.sub(r"[:;,]$", ".", text)
    if len(text) < 90:
        text = f"{text.rstrip('.')}. {suffix}" if text else suffix
    return text


def page_description(key, paragraph, suffix):
    if key in PAGE_DESCRIPTIONS:
        return PAGE_DESCRIPTIONS[key]
    WARNINGS.append(f"{key}: no hand-written description in PAGE_DESCRIPTIONS; derived one from its first paragraph")
    return meta_description(paragraph, suffix)


def iter_lines_outside_fences(lines):
    """Yield (line, in_fence) pairs."""
    fence = None
    for line in lines:
        m = re.match(r"^\s*(```+|~~~+)", line)
        if m:
            if fence is None:
                fence = m.group(1)
                yield line, True
                continue
            if line.strip().startswith(fence):
                fence = None
                yield line, True
                continue
        yield line, fence is not None



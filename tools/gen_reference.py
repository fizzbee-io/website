# --- baseline.txt normalization (rules from fizzbee's test_references.py) ---

KEEP_PREFIXES = (
    "StateSpaceOptions:",
    "Valid Nodes:",
    "IsLive:",
    "Checking ",
    "PASSED:",
    "FAILED:",
    "DEADLOCK",
    "WARNING:",
    "exists assertion",
    "Simulation is",
    "Skipping dotfile",
)
SKIP_PREFIXES = (
    "Model checking ",
    "configFileName:",
    "fizz.yaml",
    "Time taken",
    "Writen",
    "To generate",
    "To open",
    "dot ",
    "open ",
    "Downloading",
)
MAX_TRACE_LINES = 40


def clean_baseline(text):
    """Return the expected-result lines shown on the page."""
    out = []
    lines = text.splitlines()
    i = 0
    while i < len(lines):
        s = lines[i].strip()
        i += 1
        if not s:
            continue
        if re.match(r"^Nodes:\s*\d+", s):
            if re.search(r",\s*queued:\s*0\b", s):
                out.append(re.sub(r",\s*elapsed:.*$", "", s))
            continue
        if any(s.startswith(p) for p in SKIP_PREFIXES) or re.search(r"run_\d{4}-\d{2}-\d{2}", s):
            continue
        if s.startswith("FAILED:"):
            out.append(re.sub(r"\s{2,}", " ", s))
            # Keep the counterexample trace that follows, up to the file dumps.
            trace = []
            while i < len(lines) and not lines[i].startswith(("Writen", "To generate")):
                if lines[i].strip():
                    trace.append(lines[i].rstrip())
                i += 1
            if len(trace) > MAX_TRACE_LINES:
                trace = trace[:MAX_TRACE_LINES] + ["... (trace truncated)"]
            out.extend(trace)
            continue
        if any(s.startswith(p) for p in KEEP_PREFIXES):
            out.append(re.sub(r"\s{2,}", " ", s))
    return out


def parse_duration(s):
    m = re.match(r"([\d.]+)\s*(ns|µs|us|ms|s|m)\b", s)
    if not m:
        return 0.0
    v = float(m.group(1))
    return v * {"ns": 1e-9, "µs": 1e-6, "us": 1e-6, "ms": 1e-3, "s": 1, "m": 60}[m.group(2)]


def baseline_cost(text):
    """(seconds, nodes) recorded in a baseline."""
    secs = sum(parse_duration(m) for m in re.findall(r"Time taken[^:]*:\s*(\S+)", text))
    nodes = [int(n) for n in re.findall(r"^Nodes:\s*(\d+)", text, re.M)]
    return secs, max(nodes, default=0)


# --- helpers ---

def slugify(text):
    """GitHub/Hugo-style heading id."""
    s = text.strip().lower()
    s = re.sub(r"[^\w\- ]", "", s)
    return s.replace(" ", "-")


def git_lastmod(checkout, *paths):
    out = subprocess.run(
        ["git", "-C", str(checkout), "log", "-1", "--format=%cI", "--", *paths],
        capture_output=True, text=True, check=True,
    ).stdout.strip()
    return out or None


def front_matter(fields):
    lines = ["---", GENERATED_MARKER]
    for k, v in fields.items():
        if v is None:
            continue
        lines.append(f"{k}: {json.dumps(v, ensure_ascii=False)}")
    lines.append("---")
    return "\n".join(lines) + "\n"


def meta_description(text, suffix):
    """First sentence(s) of text, padded with suffix, kept under ~160 chars."""
    text = re.sub(r"\s+", " ", re.sub(r"[`*_]", "", text)).strip()
    if len(text) < 90:
        text = f"{text.rstrip('.')}. {suffix}" if text else suffix
    if len(text) > 160:
        cut = text[:157]
        text = cut[: cut.rfind(" ")].rstrip(",;:") + "..."
    return text


def iter_lines_outside_fences(lines):
    """Yield (line, in_fence) pairs."""
    fence = None
    for line in lines:
        m = re.match(r"^\s*(```+|~~~+)", line)
        if m:
            if fence is None:
                fence = m.group(1)
                yield line, True
                continue
            if line.strip().startswith(fence):
                fence = None
                yield line, True
                continue
        yield line, fence is not None


# --- examples ---

class Example:
    def __init__(self, checkout, d):
        self.dir = d
        self.name = d.name
        self.section = self.name[:2]
        self.slug = re.sub(r"^(\d\d-)+", "", self.name)
        self.rel = f"{REFS_REL}/{self.name}"
        self.files = sorted(d.glob("*.fizz"))
        self.readme = (d / "README.md").read_text() if (d / "README.md").exists() else None
        self.baseline = (d / "baseline.txt").read_text() if (d / "baseline.txt").exists() else None
        self.fizz_yaml = (d / "fizz.yaml").read_text() if (d / "fizz.yaml").exists() else None
        self.flags = (d / "flags.txt").read_text().split() if (d / "flags.txt").exists() else []
        self.lastmod = git_lastmod(checkout, self.rel)
        self.warnings = []
        self.title = self.description = self.demonstrates = None
        self._parse_header()
        self.overrides = dict(OVERRIDES.get(self.name, {}))
        if (d / "page.yaml").exists():
            import yaml  # only needed when a sidecar exists
            self.overrides.update(yaml.safe_load((d / "page.yaml").read_text()) or {})
        for k in ("title", "description", "demonstrates"):
            if self.overrides.get(k):
                setattr(self, k, self.overrides[k])
        if self.section == "13":
            default = "standalone"
        else:
            default = "embed"
        self.placement = self.overrides.get("placement", default)
        self.chapter = self.overrides.get("chapter") or EXAMPLE_CHAPTER.get(self.name) or SECTION_CHAPTER.get(self.section)
        self.anchor = None  # set once the chapter page's headings are known
        self.url = self.overrides.get("url")
        if self.placement == "standalone" and not self.url:
            self.url = f"/design/examples/{self.slug}/"
        self.source = self.files[0].read_text() if self.files else ""

    def _parse_header(self):
        if self.files:
            head = self.files[0].read_text().splitlines()[:20]
            for idx, line in enumerate(head):
                m = re.match(r"^#\s*Example\s+\d+:\s*(.+)$", line)
                if not m:
                    continue
                self.title = m.group(1).strip()
                desc, demo = [], []
                for nxt in head[idx + 1:]:
                    if not nxt.startswith("#"):
                        break
                    body = nxt.lstrip("#").strip()
                    if body.startswith("Demonstrates:"):
                        demo.append(body[len("Demonstrates:"):].strip())
                    elif demo:
                        break
                    elif body:
                        desc.append(body)
                self.description = " ".join(desc) or None
                self.demonstrates = " ".join(demo) or None
                return
        self.warnings.append("no header comments")
        # Fall back to the example's entry in references/README.md.
        entry = README_ENTRIES.get(self.name, {})
        self.title = entry.get("title") or self.slug.replace("-", " ").title()
        self.description = entry.get("purpose")
        self.demonstrates = entry.get("concepts")
        if not self.description and self.readme:
            paras = [p for p in self.readme.split("\n\n") if p.strip() and not p.startswith("#")]
            self.description = paras[0].strip() if paras else None
        if not self.description and self.files:
            self.description = leading_comment(self.files[0].read_text())

    def playground(self):
        """(allowed, note)"""
        forced = self.overrides.get("playground")
        if forced is not None:
            return bool(forced), None
        if self.flags:
            return False, f"Needs command-line flags (`{' '.join(self.flags)}`); run locally with `fizz`."
        if self.fizz_yaml:
            return False, "Uses a `fizz.yaml` config file (shown below); run locally with `fizz`."
        if self.baseline:
            secs, nodes = baseline_cost(self.baseline)
            if secs > PLAYGROUND_MAX_SECONDS or nodes > PLAYGROUND_MAX_NODES:
                return False, f"Large state space ({nodes:,} nodes); run locally with `fizz`."
        return True, None


README_ENTRIES = {}


def leading_comment(source):
    """The first comment block of a spec, skipping YAML front matter."""
    lines = source.splitlines()
    if lines and lines[0].strip() == "---":
        end = next((i for i, l in enumerate(lines[1:], 1) if l.strip() == "---"), 0)
        lines = lines[end + 1:]
    block = []
    for line in lines:
        if line.startswith("#"):
            block.append(line.lstrip("#").strip())
        elif block or line.strip():
            break
    return " ".join(b for b in block if b) or None


def parse_readme_entries(readme):
    entries = {}
    for block in re.split(r"^### ", readme, flags=re.M)[1:]:
        head, _, body = block.partition("\n")
        m = re.match(r"([\d-]+[a-z][\w-]*):\s*(.+)", head.strip())
        if not m:
            continue
        e = {"title": m.group(2).strip()}
        for key, field in (("Purpose", "purpose"), ("Key concepts", "concepts")):
            fm = re.search(rf"\*\*{key}\*\*:\s*(.+)", body)
            if fm:
                e[field] = fm.group(1).strip()
        entries[m.group(1)] = e
    return entries


def escape_html(text):
    """Header text is plain text; keep `fair<weak>` from becoming an HTML tag."""
    parts = re.split(r"(`[^`]*`)", text)
    return "".join(p if p.startswith("`") else
                   p.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
                   for p in parts)


def render_example(ex, level, link_chapter):
    """Markdown for one example. level is the heading depth for its title."""
    h = "#" * level
    out = []
    if level:
        out.append(f"{h} {escape_html(ex.title)} {{#{ex.anchor}}}\n")
    if ex.description:
        out.append(f"{escape_html(ex.description)}\n")
    if ex.demonstrates:
        out.append(f"**Demonstrates:** {escape_html(ex.demonstrates)}\n")
    if ex.readme and len(ex.files) > 1:
        body = re.sub(r"^#[^\n]*\n", "", ex.readme.strip(), count=1).strip()
        body = re.sub(r"^(#+)", lambda m: "#" * min(6, len(m.group(1)) + max(level, 1)), body, flags=re.M)
        out.append(body + "\n")
    allowed, note = ex.playground()
    sub = "#" * min(6, (level or 1) + 1)
    for f in ex.files:
        if len(ex.files) > 1:
            out.append(f"{sub} {f.name}\n")
        src = f.read_text().rstrip("\n")
        if allowed:
            out.append("{{% fizzbee %}}\n" + src + "\n{{% /fizzbee %}}\n")
        else:
            out.append(f"> {note}\n")
            out.append("```python\n" + src + "\n```\n")
    if ex.fizz_yaml:
        out.append("`fizz.yaml`:\n")
        out.append("```yaml\n" + ex.fizz_yaml.rstrip("\n") + "\n```\n")
    if ex.baseline:
        result = clean_baseline(ex.baseline)
        if result:
            out.append("**Expected result** (from `fizz`):\n")
            out.append("```\n" + "\n".join(result) + "\n```\n")
    links = [f"[Source on GitHub]({GITHUB_TREE}{ex.rel})"]
    if link_chapter:
        links.extend(link_chapter)
    out.append(" · ".join(links) + "\n")
    return "\n".join(out)


# --- language reference ---

def split_chapters(text):
    """[(title, body_lines)] for each H2 section, headings in fences ignored."""
    chapters, cur = [], None
    for line, in_fence in iter_lines_outside_fences(text.splitlines()):
        if not in_fence and line.startswith("## "):
            cur = (line[3:].strip(), [])
            chapters.append(cur)
        elif cur is not None:
            cur[1].append(line)
    return chapters


def promote_headings(lines):
    out = []
    for line, in_fence in iter_lines_outside_fences(lines):
        if not in_fence and re.match(r"^#{3,6} ", line):
            line = line[1:]
        out.append(line)
    return out


def heading_ids(lines):
    """Heading ids in a chapter body (GitHub slugs, with -N for duplicates)."""
    seen, ids = {}, []
    for line, in_fence in iter_lines_outside_fences(lines):
        m = re.match(r"^#{1,6} (.+?)\s*(\{#([\w-]+)\})?$", line) if not in_fence else None
        if not m:
            continue
        hid = m.group(3) or slugify(m.group(1))
        if hid in seen:
            seen[hid] += 1
            hid = f"{hid}-{seen[hid]}"
        else:
            seen[hid] = 0
        ids.append(hid)
    return ids


def strip_trailing_rule(lines):
    while lines and lines[-1].strip() in ("", "---"):
        lines.pop()
    while lines and not lines[0].strip():
        lines.pop(0)
    return lines


def rewrite_links(text, anchor_map, examples, page_url):
    """Point internal links at the generated pages."""
    guide_urls = {src: f"/design/reference/{slug}/" for src, slug, _ in GUIDES}
    guide_urls["README.md"] = "/design/reference/"
    guide_urls["LANGUAGE_REFERENCE.md"] = "/design/reference/"

    def repl(m):
        label, target = m.group(1), m.group(2)
        if target.startswith("#"):
            chapter = anchor_map.get(target[1:])
            if chapter is None:
                WARNINGS.append(f"{page_url}: unresolved anchor {target}")
                return m.group(0)
            url = f"/design/reference/{chapter}/"
            if target[1:] == chapter:
                return f"[{label}]({url})"
            return f"[{label}]({target if url == page_url else url + target})"
        if target in guide_urls:
            return f"[{label}]({guide_urls[target]})"
        name = target.rstrip("/")
        if name in examples:
            ex = examples[name]
            url = example_url(ex)
            if url is None:
                return m.group(0)
            if label == name:
                label = ex.title
            if url.startswith(page_url + "#"):
                url = url[len(page_url):]
            return f"[{label}]({url})"
        return m.group(0)

    return re.sub(r"(?<!!)\[([^\]]+)\]\(([^)\s]+)\)", repl, text)


def example_url(ex):
    if ex.placement == "embed" and ex.anchor:
        return f"/design/reference/{ex.chapter}/#{ex.anchor}"
    if ex.placement in ("standalone", "link"):
        return ex.url
    return f"{GITHUB_TREE}{ex.rel}"


WARNINGS = []


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("checkout", type=Path, help="path to a fizzbee-io/fizzbee checkout")
    ap.add_argument("--sample", action="store_true", help="embed only the prototype sample examples")
    args = ap.parse_args()

    checkout = args.checkout.resolve()
    refs = checkout / REFS_REL
    if not (refs / "LANGUAGE_REFERENCE.md").exists():
        sys.exit(f"error: {refs}/LANGUAGE_REFERENCE.md not found")
    commit = subprocess.run(["git", "-C", str(checkout), "rev-parse", "HEAD"],
                            capture_output=True, text=True, check=True).stdout.strip()

    readme = (refs / "README.md").read_text()
    README_ENTRIES.update(parse_readme_entries(readme))

    examples = {d.name: Example(checkout, d) for d in sorted(refs.iterdir())
                if d.is_dir() and re.match(r"^\d\d-", d.name)}
    active = {n: e for n, e in examples.items() if not args.sample or n in SAMPLE}

    # Chapters.
    chapters = []
    for title, body in split_chapters((refs / "LANGUAGE_REFERENCE.md").read_text()):
        if title in SKIP_CHAPTERS:
            continue
        chapters.append({"title": title, "slug": slugify(title), "body": strip_trailing_rule(promote_headings(body))})
    chapter_slugs = {c["slug"] for c in chapters}

    for ex in examples.values():
        if ex.placement == "embed" and ex.chapter not in chapter_slugs:
            WARNINGS.append(f"{ex.name}: chapter '{ex.chapter}' not found; excluded")
            ex.placement = "exclude"

    # Anchor ids: prose headings first, then one per embedded example.
    anchor_map = {c["slug"]: c["slug"] for c in chapters}
    for c in chapters:
        ids = heading_ids(c["body"])
        used = set(ids) | {"examples"}
        for ex in sorted(active.values(), key=lambda e: e.name):
            if ex.placement == "embed" and ex.chapter == c["slug"]:
                a = ex.slug
                if a in used:
                    a = f"example-{ex.slug}"
                ex.anchor = a
                used.add(a)
        for hid in ids:
            anchor_map.setdefault(hid, c["slug"])

    # Reverse links: chapter -> patterns using its constructs.
    pattern_constructs = {}
    for ex in active.values():
        if ex.section == "13" and ex.placement == "standalone":
            code = re.sub(r"#[^\n]*", "", ex.source)
            pattern_constructs[ex.name] = [s for s, rx in CONSTRUCT_PATTERNS
                                           if s in chapter_slugs and rx.search(code)]

    chapter_titles = {c["slug"]: c["title"] for c in chapters}
    ref_lastmod = git_lastmod(checkout, f"{REFS_REL}/LANGUAGE_REFERENCE.md")

    if REF_OUT.exists():
        shutil.rmtree(REF_OUT)
    REF_OUT.mkdir(parents=True)
    for f in EXAMPLES_OUT.glob("*.md"):
        if GENERATED_MARKER in f.read_text():
            f.unlink()

    # Landing page.
    intro = readme.split("\n\n")[1].strip()
    lines = [
        intro.replace("reference examples", "language reference and examples", 1), "",
        "## Chapters", "",
    ]
    lines += [f"- [{c['title']}](/design/reference/{c['slug']}/)" for c in chapters]
    lines += ["", "## Guides", ""]
    lines += [f"- [{t}](/design/reference/{s}/)" for _, s, t in GUIDES]
    lines += ["", "## Patterns", "",
              "Runnable specifications of common distributed-systems patterns are in the "
              "[examples catalog](/design/examples/).", ""]
    (REF_OUT / "_index.md").write_text(front_matter({
        "title": "Language Reference",
        "description": "FizzBee language reference: actions, functions, roles, flow modifiers, fairness, "
                       "assertions, fault injection and symmetry, each with runnable examples.",
        "weight": -15,
        "geekdocCollapseSection": True,
        "lastmod": ref_lastmod,
        "source": f"{GITHUB_TREE}{REFS_REL}",
        "source_commit": commit,
    }) + "\n" + "\n".join(lines))

    # Chapter pages.
    for weight, c in enumerate(chapters, start=1):
        url = f"/design/reference/{c['slug']}/"
        body = rewrite_links("\n".join(c["body"]), anchor_map, examples, url)
        embedded = sorted((e for e in active.values() if e.placement == "embed" and e.chapter == c["slug"]),
                          key=lambda e: e.name)
        if embedded:
            body += "\n\n## Examples\n\n"
            for ex in embedded:
                body += render_example(ex, 3, None) + "\n"
        users = [active[n] for n, cs in sorted(pattern_constructs.items()) if c["slug"] in cs]
        if users:
            body += "\n## Patterns that use this\n\n"
            body += "\n".join(f"- [{e.title}]({e.url})" for e in users) + "\n"
        first_para = next((p for p in "\n".join(c["body"]).split("\n\n")
                           if p.strip() and not p.lstrip().startswith(("#", "```", "-", "|", ">"))), "")
        lastmods = [m for m in [ref_lastmod] + [e.lastmod for e in embedded] if m]
        (REF_OUT / f"{c['slug']}.md").write_text(front_matter({
            "title": c["title"],
            "description": meta_description(first_para, f"FizzBee language reference: {c['title'].lower()}, with runnable examples."),
            "weight": weight,
            "lastmod": max(lastmods) if lastmods else None,
            "source": f"{GITHUB_BLOB}{REFS_REL}/LANGUAGE_REFERENCE.md#{c['slug']}",
        }) + "\n" + body.rstrip() + "\n")

    # Guides.
    for weight, (src, slug, title) in enumerate(GUIDES, start=100):
        text = (refs / src).read_text()
        text = re.sub(r"\A#\s[^\n]*\n", "", text).strip()
        url = f"/design/reference/{slug}/"
        text = rewrite_links(text, anchor_map, examples, url)
        first_para = next((p for p in text.split("\n\n") if p.strip() and not p.lstrip().startswith(("#", "```", "-", "|", ">"))), "")
        (REF_OUT / f"{slug}.md").write_text(front_matter({
            "title": title,
            "description": meta_description(first_para, f"FizzBee {title.lower()}."),
            "weight": weight,
            "lastmod": git_lastmod(checkout, f"{REFS_REL}/{src}"),
            "source": f"{GITHUB_BLOB}{REFS_REL}/{src}",
        }) + "\n" + text + "\n")

    # Pattern pages.
    for weight, ex in enumerate(sorted(active.values(), key=lambda e: e.name), start=100):
        if ex.placement != "standalone":
            continue
        related = [f"[{chapter_titles[s]}](/design/reference/{s}/)" for s in pattern_constructs.get(ex.name, [])]
        body = render_example(ex, 0, None)
        if related:
            body += "\n## Language features used\n\n" + ", ".join(related) + "\n"
        desc = ex.description or ex.title
        (EXAMPLES_OUT / f"{ex.slug}.md").write_text(front_matter({
            "title": ex.title,
            "description": meta_description(f"{ex.title} modeled in FizzBee: {desc}",
                                            "Runnable formal specification with model-checker results."),
            "weight": weight,
            "lastmod": ex.lastmod,
            "source": f"{GITHUB_TREE}{ex.rel}",
        }) + "\n" + body.rstrip() + "\n")

    # Report.
    print(f"fizzbee commit {commit}{' (sample)' if args.sample else ''}")
    for ex in sorted(examples.values(), key=lambda e: e.name):
        if ex.name not in active:
            continue
        where = {"embed": f"embedded in {ex.chapter}#{ex.anchor}", "standalone": f"page {ex.url}",
                 "link": f"linked to {ex.url} ({ex.overrides.get('reason', '')})",
                 "exclude": f"excluded ({ex.overrides.get('reason', 'no chapter')})"}[ex.placement]
        allowed, _ = ex.playground()
        print(f"  {ex.name:45s} {where}{'' if allowed else '  [no playground]'}")
    warnings = WARNINGS + [f"{ex.name}: {w}" for ex in sorted(active.values(), key=lambda e: e.name) for w in ex.warnings]
    for w in warnings:
        print(f"warning: {w}", file=sys.stderr)
    print(f"{len(chapters)} chapters, {len(GUIDES)} guides, "
          f"{sum(e.placement == 'standalone' for e in active.values())} pattern pages, "
          f"{len(warnings)} warnings")


if __name__ == "__main__":
    main()
